"""Markdown analysis generation from benchmark CSV files."""

from __future__ import annotations

from pathlib import Path
import csv

from homotopy_path_learning.config import Phase6Config
from homotopy_path_learning.evaluation.metrics import SUMMARY_FIELDS, read_rows, summarize_rows


def generate_summary_markdown(
    *,
    config: Phase6Config,
    run_id: str,
    benchmark_csv: str | Path,
    checkpoint: str,
    git_commit: str,
    output_path: str | Path,
) -> Path:
    """Generate a Markdown summary by reading benchmark CSV data."""

    rows = read_rows(benchmark_csv)
    summaries = summarize_rows(rows)
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    header = [
        f"# {config.experiment.id} {config.experiment.name}",
        "",
        "This is a short Phase 6 smoke test for pipeline validation, not a performance conclusion.",
        "",
        f"- Experiment ID: {config.experiment.id}",
        f"- Run ID: {run_id}",
        f"- Git commit: {git_commit}",
        f"- Checkpoint: `{checkpoint}`",
        f"- Evaluation instances: {config.evaluation.num_instances}",
        f"- Degrees: {list(config.system.degrees)}",
        f"- Bezier degree: {config.path.bezier_degree}",
        f"- Latent dimension: {config.path.latent_dim}",
        f"- Tracker max steps: {config.tracker.max_steps}",
        f"- PPO total timesteps: {config.ppo.total_timesteps}",
        f"- PPO rollout steps: {config.ppo.rollout_steps}",
        "",
        "## Method Summary",
        "",
        "| Method | Problem Success | Path Success | Mean Cost | Median Cost | Std ddof=0 | Mean Improvement | Positive Improvement | Max Residual | Time s |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    lines = list(header)
    for summary in summaries:
        lines.append(
            "| {method} | {problem_success_rate:.6g} | {path_success_rate:.6g} | "
            "{mean_cost:.6g} | {median_cost:.6g} | {std_cost_ddof0:.6g} | "
            "{mean_improvement_vs_linear:.6g} | {positive_improvement_rate:.6g} | "
            "{maximum_residual_norm:.6g} | {total_elapsed_seconds:.6g} |".format(**summary)
        )
    failed_paths = sum(int(row["n_failed"]) for row in rows)
    lines.extend(
        [
            "",
            "## Notes",
            "",
            f"- Tracking failed paths: {failed_paths}",
            "- Standard deviation uses population standard deviation (`ddof=0`).",
            "- Rewards are not clipped or normalized.",
            "- Actions are generated by a tanh-squashed Gaussian policy without clipping.",
        ]
    )
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output


def read_summary_csv(path: str | Path) -> list[dict[str, str]]:
    """Read benchmark summary CSV with the expected header."""

    with Path(path).open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != SUMMARY_FIELDS:
            raise ValueError("benchmark summary CSV has an unexpected header.")
        return list(reader)


__all__ = ["generate_summary_markdown", "read_summary_csv"]
